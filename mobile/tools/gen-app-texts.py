"""Writes an app's built-in Admin texts (the fallback wording) from the server's standard catalogue.

    python mobile/tools/gen-app-texts.py app.msme > mobile/apps/msme/src/content/builtInTexts.ts

Source: backend/src/Zed.Core/Content/ContentCatalogue.Apps.cs (docs/mobile/APP-TEXTS.md). Run from the repository root.
"""
import json
import re
import sys
import textwrap

prefix = sys.argv[1] if len(sys.argv) > 1 else 'app.msme'
src = open('backend/src/Zed.Core/Content/ContentCatalogue.Apps.cs', encoding='utf-8').read()
entry = re.compile(
    r'App\("(' + re.escape(prefix) + r'\.[^"]+)",\s*"([^"]+)",\s*\w+,\s*(\w+),\s*'
    r'(?:"""(.*?)"""|"((?:[^"\\]|\\.)*)")',
    re.S,
)
rows = []
for m in entry.finditer(src):
    key, name, systems, raw, plain = m.groups()
    if raw is not None:
        text = textwrap.dedent(raw).strip()
        if text.startswith('<'):
            text = re.sub(r'\n\s*', '', text)
    else:
        text = re.sub(r'\\(.)', r'\1', plain)
    rows.append((key, name, systems, text))

out = sys.stdout
out.reconfigure(encoding='utf-8', newline='\n')
out.write('// Generated by mobile/tools/gen-app-texts.py from backend/src/Zed.Core/Content/ContentCatalogue.Apps.cs:\n')
out.write("// the standard wording (the legacy app's own), shown until the server's Admin texts arrive. Do not edit.\n")
out.write('export const BUILT_IN_TEXTS: Readonly<Record<string, string>> = {\n')
for key, name, systems, text in rows:
    out.write(f'  // {name} ({systems})\n')
    out.write(f'  {json.dumps(key)}: {json.dumps(text, ensure_ascii=False)},\n')
out.write('};\n')
print(f'{len(rows)} texts', file=sys.stderr)
