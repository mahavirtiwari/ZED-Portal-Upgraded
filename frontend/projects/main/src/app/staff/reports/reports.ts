import { HttpClient } from '@angular/common/http';
import { Component, computed, inject, signal } from '@angular/core';
import { apiErrorMessage } from '@zed/shared';
import { firstValueFrom } from 'rxjs';
import { ListSearchComponent, searchRows } from '../pager';
import { DashboardPortalSwitchComponent } from '../dashboard-portal-switch';
import { PageHead } from '../../msme/shared/page-head';

export interface ReportItem {
  id: string;
  name: string;
}

/** Reads the problem title out of a failed blob response (the API sends problem+json on errors). */
async function blobError(err: unknown): Promise<string> {
  const e = err as { error?: unknown };
  if (e?.error instanceof Blob) {
    try {
      const title = (JSON.parse(await e.error.text()) as { title?: string }).title;
      if (title) return title;
    } catch {
      /* not JSON */
    }
  }
  return apiErrorMessage(err);
}

/**
 * Reports. Port of Views/DynamicReports/Index.cshtml: the reports of the signed-in role, each downloaded as
 * an Excel file generated by the API. The page only sends a report id; the API decides the procedure.
 */
@Component({
  selector: 'zed-staff-reports',
  imports: [ListSearchComponent, DashboardPortalSwitchComponent, PageHead],
  host: { class: 'list-v2 d-block' },
  template: `
    <!-- One Dashboard Admin (2026-11-07): the portal of this screen. -->
    <zed-dashboard-portal-switch [screens]="['reports']" />
    <!-- 2026-11-14 (approved frame A): the shared header and the reports in one card (each downloads as Excel: no filters to show). -->
    <zed-page-head [crumbs]="[{ label: 'Home', link: '/staff' }, { label: 'Reports' }]" title="Reports" />
    @if (error()) { <div class="alert alert-danger" role="alert">{{ error() }}</div> }
    <div class="list-card reports">
    <div class="list-card-head">
      <b>{{ reports().length }} reports <small class="sub d-inline">· each downloaded as an Excel file</small></b>
      <zed-list-search [(value)]="search" placeholder="Search reports" inputId="reports-search" [found]="shown().length" />
    </div>
    <div class="table-responsive">
      <table class="table table-zed">
        <thead>
          <tr>
            <th style="width: 70px">S.No</th>
            <th>Report Name</th>
            <th style="width: 150px">Download</th>
          </tr>
        </thead>
        <tbody>
          @for (r of shown(); track r.id) {
            <tr>
              <td>{{ $index + 1 }}</td>
              <td><strong>{{ r.name }}</strong></td>
              <td>
                <div class="row-actions">
                  <button type="button" class="btn btn-primary" [disabled]="downloading() !== null"
                          (click)="download(r)">{{ downloading() === r.id ? 'PLEASE WAIT' : 'DOWNLOAD' }}</button>
                </div>
              </td>
            </tr>
          } @empty {
            @if (loaded()) { <tr><td colspan="3" style="padding: 0"><div class="no-data">{{ reports().length ? 'No report matches the search.' : 'No reports' }}</div></td></tr> }
          }
        </tbody>
      </table>
    </div>
    </div>
    @if (downloading()) {
      <div class="loadingdiv" style="display: block" role="status" aria-live="polite"><div class="loadingimage"><div class="loader"></div><div class="text-center"><small>Please wait ... large reports may take a few minutes.</small></div></div></div>
    }
  `,
  styles: `
    .loadingdiv { position: fixed; inset: 0; background: rgba(0,0,0,.35); display: flex; align-items: center; justify-content: center; z-index: 2000; }
    .reports { max-width: 960px; }
  `,
})
export class ReportsPage {
  private readonly http = inject(HttpClient);

  protected readonly reports = signal<ReportItem[]>([]);
  /** The search box above the list. */
  protected readonly search = signal('');
  protected readonly shown = computed(() => searchRows(this.reports(), this.search()));
  protected readonly loaded = signal(false);
  protected readonly error = signal('');
  protected readonly downloading = signal<string | null>(null);

  constructor() {
    void this.load();
  }

  private async load(): Promise<void> {
    try {
      this.reports.set(await firstValueFrom(this.http.get<ReportItem[]>('/api/staff/reports')));
    } catch (err) {
      this.error.set(apiErrorMessage(err));
    } finally {
      this.loaded.set(true);
    }
  }

  protected async download(report: ReportItem): Promise<void> {
    this.error.set('');
    this.downloading.set(report.id);
    try {
      const blob = await firstValueFrom(
        this.http.get(`/api/staff/reports/${encodeURIComponent(report.id)}/download`, { responseType: 'blob' }),
      );
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = report.name.replace(/[^A-Za-z0-9-]/g, '_') + '.xlsx';
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch (err) {
      this.error.set(await blobError(err));
    } finally {
      this.downloading.set(null);
    }
  }
}
